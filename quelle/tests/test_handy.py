"""Design-Review Stufe 4: Handy-Bedienung – Werkzeuge unten, Blätter von unten, lesbarer Start-Zoom."""
import sys,os; sys.path.insert(0,os.path.dirname(os.path.abspath(__file__))); from hilfe import *
from playwright.sync_api import sync_playwright
srv=server()
try:
 with sync_playwright() as p:
  br=p.chromium.launch(executable_path=CHROME); errs=[]
  ctx=br.new_context(viewport={'width':390,'height':844},has_touch=True,is_mobile=True); pg=ctx.new_page(); pg.on('pageerror',lambda e: errs.append(str(e)))
  pg.goto(URL); pg.wait_for_timeout(1000)
  r=pg.evaluate("()=>{const b=document.getElementById('phoneBar').getBoundingClientRect();return [document.body.classList.contains('phone'),b.bottom,innerHeight,b.height,getComputedStyle(document.getElementById('tools')).display,getComputedStyle(document.getElementById('palHandle')).display]}")
  check('Werkzeugleiste unten, oben keine Werkzeuge, keine Seitengriffe',r[0] and abs(r[1]-r[2])<1 and r[3]>=56 and r[4]=='none' and r[5]=='none',str(r))
  k=pg.evaluate("()=>{const m=/scale\\(([\\d.]+)\\)/.exec(document.getElementById('world').getAttribute('transform')||'');return m?+m[1]:null}")
  check('Start-Zoom lesbar (mind. 75 %)',k is not None and k>=0.749,str(k))
  pg.tap('#pbPlus'); pg.wait_for_timeout(250)
  pr=pg.evaluate("()=>{const r=document.getElementById('palette').getBoundingClientRect();return [r.left,r.width,innerWidth]}")
  check('„+“ öffnet die Formen als Blatt über die volle Breite',pg.is_visible('#palette .pal') and pr[0]<=1 and pr[1]>=388,str(pr))
  n=len(pg.evaluate(READ)['items']); pg.tap('.pal[data-kind="rect"]'); pg.wait_for_timeout(400)
  check('Form antippen fügt sie ein und schließt das Blatt',len(pg.evaluate(READ)['items'])==n+1 and pg.evaluate("document.querySelector('main').classList.contains('pal-closed')"))
  c=pg.evaluate("()=>{const r=document.getElementById('props').getBoundingClientRect(),b=document.getElementById('phoneBar').getBoundingClientRect();return [r.bottom<=b.top+1,r.left>=0,r.right<=innerWidth]}")
  check('Optionsleiste liegt über der Werkzeugleiste',all(c),str(c))
  pg.tap('#props [data-drop="fill"]'); pg.wait_for_timeout(250)
  cp=pg.evaluate("()=>{const r=document.getElementById('colorPop').getBoundingClientRect();return [r.top>=0,r.bottom<=innerHeight,r.left>=0,r.right<=innerWidth]}")
  check('Farbauswahl ganz sichtbar',all(cp),str(cp)); pg.keyboard.press('Escape')
  pg.tap('#pbMore'); pg.wait_for_timeout(200)
  check('„Mehr“ öffnet das Blatt',pg.is_visible('#moreSheet [data-tool="brush"]') and pg.is_visible('#moreSheet [data-ms="help"]'))
  pg.tap('#moreSheet [data-tool="brush"]'); pg.wait_for_timeout(150)
  check('Pinsel aus „Mehr“ gewählt, „Mehr“ markiert',pg.is_hidden('#moreSheet') and pg.evaluate("document.getElementById('pbMore').classList.contains('on')") and pg.get_attribute('#tools [data-tool="brush"]','aria-pressed')=='true')
  pg.tap('#phoneBar [data-tool="select"]'); pg.tap('#pbMore'); pg.tap('#moreSheet [data-ms="files"]'); pg.wait_for_timeout(250)
  check('„Boards“ öffnet die Datei-Leiste als Blatt',pg.is_visible('#menu [data-m="new"]') and pg.evaluate("document.getElementById('menu').getBoundingClientRect().width")>=388)
  pg.mouse.click(200,120); pg.wait_for_timeout(200)
  pg.tap('#pbMore'); pg.tap('#moreSheet [data-ms="help"]'); pg.wait_for_timeout(200)
  check('Hilfe auf dem Handy erreichbar, mit Gesten',pg.is_visible('#helpStart') and 'Doppeltippen' in pg.inner_text('#helpStart')); pg.tap('#keysX')
  pg.tap('#liveBtn'); pg.wait_for_timeout(200)
  lp=pg.evaluate("()=>{const r=document.getElementById('livePop').getBoundingClientRect();return [r.left<=1,r.width>=388,r.bottom<=document.getElementById('phoneBar').getBoundingClientRect().top+1]}")
  check('Teilen-Menü als Blatt von unten',all(lp),str(lp))
  check('Keine Fehler',not errs,str(errs)); ctx.close()
  pg=br.new_page(viewport={'width':1280,'height':800}); pg.goto(URL); pg.wait_for_timeout(500)
  check('Am Computer keine Handy-Leiste',pg.is_hidden('#phoneBar') and pg.is_visible('#tools'))
  br.close()
finally: srv.terminate()
